    """
    Возвращает локализованную строку для заданного языка и ключа.
    Поддерживает форматирование через kwargs (например, t("ru", "welcome", name="Иван")).
    Фолбэк: если язык не найден — используется "ru".
    Безопасно обрабатывает форматирование: при отсутствии ключа не падает с KeyError.
    """
