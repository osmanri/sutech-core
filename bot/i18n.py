def t(lang: str, key: str, **kwargs) -> str:
    """
    Возвращает локализованную строку для заданного языка и ключа.
    Поддерживает форматирование через kwargs (например, t("ru", "welcome", name="Иван")).
    Фолбэк: если язык не найден — используется "ru".
    Безопасно обрабатывает форматирование: при отсутствии ключа не падает с KeyError.
    """
    text = STRINGS.get(lang, STRINGS["ru"]).get(key, STRINGS["ru"].get(key, key))
    if not kwargs:
        return text
    try:
        return text.format(**kwargs)
    except KeyError:
        import string
        class SafeDict(dict):
            def __missing__(self, k):
                return f"{{{k}}}"
        return string.Formatter().vformat(text, (), SafeDict(kwargs))
