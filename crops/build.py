"""Build everything that depends on the crop list from crops/catalog.json (the single source of truth).

    python3 crops/build.py          # write the generated files
    python3 crops/build.py --check  # fail if a generated file is out of date (used by tests and CI)

Generated: bot/crops_data.py (Python engine), serverless/tgcloud/lib/crops-data.js (bot and website engine),
crops/crops-catalog.js (Mini App picker; copied to sutech-frontend/js/crops-catalog.js), and the crop-name blocks
inside bot/i18n.py (between the BEGIN/END GENERATED CROP NAMES markers).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = json.loads((ROOT / "crops" / "catalog.json").read_text(encoding="utf-8"))
CROPS = CATALOG["crops"]
RICE_SALT = [3.0, 12.0]   # FAO-56 Table 23 (rice is handled by its own routine, not by the table)
HEADER = "# GENERATED by crops/build.py from crops/catalog.json. Do not edit; edit the catalog and rebuild.\n"


def num(x: float) -> str:
    return repr(float(x))


def python_module() -> str:
    lines = [HEADER, '"""Crop table of the Python engine: p, root depth min/max, Kc ini/mid/end, stage days; salt tolerance."""\n\n', "CROPS = {\n"]
    for c in CROPS:
        lines.append(f"    {c['key']!r}: ({num(c['p'])}, {num(c['root'][0])}, {num(c['root'][1])}, "
                     f"({', '.join(num(v) for v in c['kc'])}), ({', '.join(str(v) for v in c['stages'])})),\n")
    lines.append("}\n\nSALT_TOLERANCE = {\n")
    for c in CROPS:
        if c["salt"]:
            lines.append(f"    {c['key']!r}: ({num(c['salt'][0])}, {num(c['salt'][1])}),\n")
    lines.append(f"    'rice': ({num(RICE_SALT[0])}, {num(RICE_SALT[1])}),\n}}\n\nCROP_STATUS = {{\n")
    for c in CROPS:
        lines.append(f"    {c['key']!r}: {c['status']!r},\n")
    lines.append("}\n")
    return "".join(lines)


def js_module() -> str:
    lines = [HEADER.replace("# ", "// "), "// Crop table of the JavaScript engine: [p, root min, root max, [Kc ini, mid, end], [stage days]]; salt [ECe threshold, slope].\n", "export const CROPS_DATA = {\n"]
    for c in CROPS:
        lines.append(f"  {c['key']}:[{num(c['p'])},{num(c['root'][0])},{num(c['root'][1])},[{','.join(num(v) for v in c['kc'])}],[{','.join(str(v) for v in c['stages'])}]],\n")
    lines.append("};\nexport const SALT_DATA = {\n")
    for c in CROPS:
        if c["salt"]:
            lines.append(f"  {c['key']}:[{num(c['salt'][0])},{num(c['salt'][1])}],\n")
    lines.append(f"  rice:[{num(RICE_SALT[0])},{num(RICE_SALT[1])}],\n}};\nexport const CROP_STATUS = {json.dumps({c['key']: c['status'] for c in CROPS})};\n")
    return "".join(lines)


def picker_module() -> str:
    items = [dict(key=c["key"], names=c["names"], group=c["group"], stages=c["stages"], status=c["status"]) for c in CROPS]
    return ("// GENERATED by crops/build.py from crops/catalog.json. Do not edit.\n// Crop list for the Mini App picker: names in three languages, default stage calendar, source status.\n"
            f"window.SU_CROPS = {json.dumps(items, ensure_ascii=False, indent=1)};\n")


BEGIN, END = "# BEGIN GENERATED CROP NAMES", "# END GENERATED CROP NAMES"


def i18n_text() -> str:
    path = ROOT / "bot" / "i18n.py"
    text = path.read_text(encoding="utf-8")
    # drop earlier generated blocks
    out, skip = [], False
    for line in text.split("\n"):
        if BEGIN in line:
            skip = True
            continue
        if END in line:
            skip = False
            continue
        if not skip:
            out.append(line)
    text = "\n".join(out)
    lang_anchor = {"ru": '        "report_crop_sunflower": "Подсолнечник",', "kz": '        "report_crop_sunflower": "Күнбағыс",',
                   "en": "    'report_crop_other': 'Other crop', 'report_crop_sunflower': 'Sunflower',"}
    base = text
    for lang, anchor in lang_anchor.items():
        assert text.count(anchor) == 1, anchor
        lines = []
        for c in CROPS:
            key = f"report_crop_{c['key']}"
            if f'"{key}"' in base or f"'{key}'" in base:
                continue
            name = c["names"][lang]
            lines.append(f'        "{key}": "{name}",' if lang != "en" else f"    '{key}': '{name}',")
        if lines:
            indent = "        " if lang != "en" else "    "
            block = f"{indent}{BEGIN}\n" + "\n".join(lines) + f"\n{indent}{END}"
            text = text.replace(anchor, anchor + "\n" + block, 1)
    return text


def targets() -> dict[Path, str]:
    return {ROOT / "bot" / "crops_data.py": python_module(), ROOT / "serverless" / "tgcloud" / "lib" / "crops-data.js": js_module(),
            ROOT / "crops" / "crops-catalog.js": picker_module(), ROOT / "bot" / "i18n.py": i18n_text()}


def main() -> int:
    stale = []
    for path, content in targets().items():
        if path.exists() and path.read_text(encoding="utf-8") == content:
            continue
        if "--check" in sys.argv:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content, encoding="utf-8")
            print("wrote", path.relative_to(ROOT))
    if stale:
        print("out of date, run python3 crops/build.py:", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
